#include "assist_protocol.h"
#include <cassert>
#include <iostream>

using Event = AssistProtocol::Event;
int main() {
    AssistProtocol p;
    assert(p.receive(R"({"type":"auth_required"})") == Event::Authenticate);
    assert(!p.authenticated && !p.streaming);
    assert(p.receive(R"({"type":"auth_ok"})") == Event::Ready);
    assert(p.authenticated);
    JsonDocument command;
    assert(!deserializeJson(command, p.begin("my-pipeline")));
    assert(command["id"] == 1 && command["pipeline"] == "my-pipeline");
    assert(command["start_stage"] == "wake_word" && command["end_stage"] == "intent");
    assert(command["input"]["sample_rate"] == 16000);
    assert(command["input"]["auto_gain_dbfs"] == 0);
    assert(p.running && !p.streaming);
    assert(!p.gate_wake_audio());
    p.receive(R"({"id":99,"type":"event","event":{"type":"run-start","data":{"runner_data":{"stt_binary_handler_id":8}}}})");
    assert(!p.streaming); // Stale/unrelated runs must not change the audio routing.
    p.receive(R"({"id":1,"type":"event","event":{"type":"run-start","data":{"runner_data":{"stt_binary_handler_id":7}}}})");
    assert(p.streaming && p.handler == 7);
    assert(p.gate_wake_audio());
    p.stop_streaming = true;
    assert(!p.gate_wake_audio()); // Stop capture must never be speech-gated.
    p.stop_streaming = false;
    assert(p.receive(R"({"id":1,"type":"result","success":true})") == Event::None);
    assert(p.streaming);
    p.receive(R"({"id":1,"type":"event","event":{"type":"wake_word-end","data":{}}})");
    assert(!p.command_active); // Silence timeout is not a wake word.
    assert(p.receive(R"({"id":1,"type":"event","event":{"type":"wake_word-end","data":{"wake_word_output":{"wake_word_id":"hey_jarvis"}}}})") == Event::Wake);
    assert(p.command_active);
    assert(!p.gate_wake_audio());
    assert(p.receive(R"({"id":1,"type":"event","event":{"type":"stt-end","data":{"stt_output":{"text":"turn on the light"}}}})") == Event::Transcript);
    assert(p.transcript() == "turn on the light");
    p.receive(R"({"id":1,"type":"event","event":{"type":"stt-end"}})");
    assert(!p.streaming && p.command_active); // Keep music ducked until intent completes.
    assert(p.receive(R"({"id":1,"type":"event","event":{"type":"run-end"}})") == Event::Finished);
    assert(!p.running && !p.command_active);
    deserializeJson(command, p.begin(""));
    assert(command["id"] == 2 && command["pipeline"].isNull());
    p.receive(R"({"id":1,"type":"event","event":{"type":"error"}})");
    assert(p.running); // Late previous-run errors cannot cancel a new run.
    assert(p.receive(R"({"id":2,"type":"result","success":false})") == Event::Error);
    assert(!p.running);
    p.begin("");
    assert(p.receive(R"({"id":3,"type":"event","event":{"type":"run-start","data":{"runner_data":{"stt_binary_handler_id":256}}}})") == Event::Error);
    assert(!p.running && !p.streaming);
    p.begin("");
    assert(p.receive("not json") == Event::Error && !p.running);
    p.begin("");
    assert(p.receive(R"({"type":"auth_invalid"})") == Event::AuthInvalid);
    assert(!p.authenticated && !p.running && !p.streaming && !p.command_active);
    p.receive(R"({"type":"auth_ok"})");
    p.begin("");
    assert(p.receive(R"({"id":6,"type":"event","event":{"type":"error","data":{"code":"wake-word-timeout"}}})") == Event::Finished);
    assert(!p.running && !p.streaming);
    // The TTS answer must become one announcement, using a distinct, monotonic ID.
    AssistProtocol reply;
    reply.receive(R"({"type":"auth_ok"})");
    deserializeJson(command, reply.begin("", true));
    assert(command["end_stage"] == "tts");
    assert(reply.receive(R"({"id":99,"type":"event","event":{"type":"tts-end","data":{"tts_output":{"url":"/wrong.wav"}}}})") == Event::None);
    assert(reply.receive(R"({"id":1,"type":"event","event":{"type":"tts-end","data":{"tts_output":{"media_id":"media-source://tts/answer","url":"/api/tts_proxy/answer.wav","mime_type":"audio/wav"}}}})") == Event::SpeechReady);
    assert(!reply.command_active && !reply.streaming);
    assert(reply.announcement("light.wrong", "ws://haos.home:8123/api/websocket").empty());
    deserializeJson(command, reply.announcement("media_player.test", "ws://haos.home:8123/api/websocket"));
    assert(command["id"] == 2 && command["type"] == "call_service");
    assert(command["target"]["entity_id"] == "media_player.test");
    assert(command["service_data"]["media_content_id"] == "media-source://tts/answer");
    assert(command["service_data"]["announce"] == true);
    assert(command["service_data"]["extra"]["use_pre_announce"] == false);
    assert(reply.announcement_pending);
    assert(reply.announcement("media_player.test", "ws://haos.home:8123/api/websocket").empty());
    assert(reply.receive(R"({"id":1,"type":"event","event":{"type":"tts-end"}})") == Event::None);
    reply.receive(R"({"id":1,"type":"event","event":{"type":"run-end"}})");
    assert(!reply.running && reply.announcement_pending);
    assert(reply.receive(R"({"id":2,"type":"result","success":true})") == Event::PlaybackAccepted);
    assert(!reply.announcement_pending);
    deserializeJson(command, reply.begin("", true));
    assert(command["id"] == 3);
    reply.receive(R"({"id":3,"type":"event","event":{"type":"tts-end","data":{"tts_output":{"url":"/api/tts_proxy/a.wav"}}}})");
    deserializeJson(command, reply.announcement("media_player.test", "wss://haos.home:8123/api/websocket"));
    assert(command["id"] == 4);
    assert(command["service_data"]["media_content_id"] == "https://haos.home:8123/api/tts_proxy/a.wav");
    assert(reply.receive(R"({"id":4,"type":"result","success":false})") == Event::PlaybackFailed);
    assert(!reply.announcement_pending);
    reply.reset();
    assert(!reply.command_active && !reply.announcement_pending && !reply.streaming);
    reply.begin("", true);
    reply.receive(R"({"id":5,"type":"event","event":{"type":"tts-end","data":{"tts_output":{"url":"file:///tmp/a.wav"}}}})");
    assert(reply.announcement("media_player.test", "ws://haos.home:8123/api/websocket").empty());
    assert(!reply.announcement_pending);
    AssistProtocol sync;
    assert(sync.receive(R"({"type":"auth_ok"})") == Event::Ready);
    deserializeJson(command, sync.subscribe_control());
    assert(command["id"] == 1 && command["type"] == "subscribe_entities");
    assert(command["entity_ids"][0] == "input_button.johan2_assist_start");
    assert(command["entity_ids"][1] == "input_button.johan2_assist_cancel");
    deserializeJson(command, sync.begin("", true, "shared-conversation", true));
    assert(command["id"] == 2 && command["start_stage"] == "stt");
    assert(command["conversation_id"] == "shared-conversation");
    assert(sync.receive(R"({"id":99,"type":"event","event":{"c":{"input_button.johan2_assist_start":{"+":{"s":"new"}}}}})") == Event::None);
    assert(sync.receive(R"({"id":1,"type":"event","event":{"a":{"input_button.johan2_assist_start":{"s":"old"}}}})") == Event::None);
    assert(sync.receive(R"({"id":1,"type":"event","event":{"c":{"input_button.johan2_assist_start":{"+":{"s":"old"}}}}})") == Event::None);
    assert(sync.receive(R"({"id":1,"type":"event","event":{"c":{"input_button.johan2_assist_start":{"+":{"s":"new"}}}}})") == Event::RemoteStart);
    assert(sync.receive(R"({"id":1,"type":"event","event":{"c":{"input_button.johan2_assist_start":{"+":{"s":"new"}}}}})") == Event::None);
    assert(sync.receive(R"({"id":1,"type":"event","event":{"c":{"input_button.johan2_assist_cancel":{"+":{"s":"new"}}}}})") == Event::RemoteCancel);
    assert(sync.receive(R"({"id":1,"type":"event","event":{"c":{"input_button.johan2_assist_start":{"+":{"s":"unavailable"}}}}})") == Event::None);
    assert(sync.receive(R"({"id":1,"type":"result","success":false,"error":{"code":"unauthorized"}})") == Event::SyncError);
    deserializeJson(command, sync.state_update("listening"));
    assert(command["id"] == 3 && command["target"]["entity_id"] == "input_select.johan2_assist_state");
    assert(command["service_data"]["option"] == "listening");
    assert(sync.run_id == 2); // UI/service traffic must not replace the active run.
    assert(sync.receive(R"({"id":3,"type":"result","success":true})") == Event::None);
    sync.receive(R"({"id":2,"type":"event","event":{"type":"run-start","data":{"runner_data":{"stt_binary_handler_id":7}}}})");
    assert(sync.streaming);
    assert(sync.receive(R"({"id":2,"type":"event","event":{"type":"stt-start"}})") == Event::Listening);
    assert(sync.command_active);
    assert(sync.receive(R"({"id":2,"type":"event","event":{"type":"stt-vad-end"}})") == Event::Processing);
    assert(sync.receive(R"({"id":2,"type":"event","event":{"type":"stt-end","data":{"stt_output":{"text":""}}}})") == Event::Processing);
    assert(!sync.streaming);
    sync.reset();
    assert(sync.receive(R"({"id":1,"type":"event","event":{"c":{"input_button.johan2_assist_start":{"+":{"s":"later"}}}}})") == Event::None);
    deserializeJson(command, sync.begin(""));
    assert(command["id"] == 4 && command["start_stage"] == "wake_word");
    assert(sync.receive(R"({"id":2,"type":"event","event":{"type":"stt-start"}})") == Event::None);
    AssistProtocol cancel;
    cancel.begin("", false, nullptr, false);
    cancel.receive(R"({"id":1,"type":"event","event":{"type":"run-start","data":{"runner_data":{"stt_binary_handler_id":1}}}})");
    deserializeJson(command, cancel.cancel_run());
    assert(command["type"] == "unsubscribe_events" && command["subscription"] == 1);
    assert(!cancel.running && !cancel.streaming && !cancel.command_active);
    deserializeJson(command, cancel.begin("", false, nullptr, true));
    assert(command["id"] == 3 && command["start_stage"] == "stt");
    assert(cancel.receive(R"({"id":1,"type":"event","event":{"type":"run-end"}})") == Event::None);
    assert(cancel.running);
    assert(cancel.receive(R"({"id":3,"type":"event","event":{"type":"error","data":{"code":"stt-no-text-recognized"}}})") == Event::Error);
    assert(cancel.error_code() == "stt-no-text-recognized");
    deserializeJson(command, cancel.begin_stop("pl"));
    assert(command["id"] == 4 && command["start_stage"] == "stt" && command["end_stage"] == "stt" && cancel.stop_running);
    cancel.receive(R"({"id":4,"type":"event","event":{"type":"run-start","data":{"runner_data":{"stt_binary_handler_id":9}}}})");
    assert(cancel.stop_streaming && cancel.active_handler() == 9);
    assert(cancel.receive(R"({"id":4,"type":"event","event":{"type":"stt-end","data":{"stt_output":{"text":"stop"}}}})") == Event::StopTranscript);
    assert(cancel.stop_transcript() == "stop" && !cancel.stop_streaming);
    cancel.receive(R"({"id":4,"type":"event","event":{"type":"run-end"}})");
    assert(!cancel.stop_running);
    deserializeJson(command, cancel.cancel_stop());
    assert(command["type"] == "unsubscribe_events");
    AssistProtocol unclear;
    unclear.begin("", true, nullptr, true);
    assert(!unclear.unclear && !unclear.speech_started);
    unclear.receive(R"({"id":1,"type":"event","event":{"type":"stt-vad-start"}})");
    assert(unclear.speech_started);
    unclear.receive(R"({"id":1,"type":"event","event":{"type":"intent-end","data":{"intent_output":{"response":{"response_type":"error","data":{"code":"no_intent_match"}}}}}})");
    assert(unclear.unclear);
    unclear.begin("", true, nullptr, true);
    assert(unclear.receive(R"({"id":2,"type":"event","event":{"type":"error","data":{"code":"stt-no-text-recognized"}}})") == Event::Error);
    assert(unclear.unclear);
    unclear.begin("", true, nullptr, true);
    unclear.receive(R"({"id":3,"type":"event","event":{"type":"intent-end","data":{"intent_output":{"continue_conversation":true,"response":{"response_type":"action_done"}}}}})");
    assert(unclear.continue_conversation && !unclear.unclear);
    unclear.begin("", true, nullptr, true);
    unclear.receive(R"({"id":4,"type":"event","event":{"type":"intent-end","data":{"intent_output":{"response":{"response_type":"action_done","speech":{"plain":{"speech":"Welke kamer? "}}}}}}})");
    assert(unclear.continue_conversation);
    unclear.begin("", true, nullptr, true);
    unclear.receive(R"({"id":5,"type":"event","event":{"type":"intent-end","data":{"intent_output":{"response":{"response_type":"action_done","speech":{"plain":{"speech":"Klaar."}}}}}}})");
    assert(!unclear.continue_conversation);
    assert(!unclear.wants_followup(true, true));
    unclear.continue_conversation = true;
    assert(unclear.wants_followup(false, false));
    assert(!unclear.wants_followup(true, true)); // VAD alone cannot repeat a question.
    unclear.receive(R"({"id":5,"type":"event","event":{"type":"stt-end","data":{"stt_output":{"text":"Keuken"}}}})");
    assert(unclear.wants_followup(true, true));
    unclear.begin("", true, nullptr, true);
    assert(unclear.transcript().empty());
    unclear.unclear = true;
    assert(unclear.wants_followup(false, false));
    assert(!unclear.wants_followup(true, true));
    unclear.reset();
    assert(!unclear.unclear && !unclear.continue_conversation && !unclear.speech_started);
    AssistProtocol fixed_gain;
    deserializeJson(command, fixed_gain.begin("", true, nullptr, true));
    assert(command["start_stage"] == "stt" && command["input"]["auto_gain_dbfs"] == 0);
    deserializeJson(command, fixed_gain.begin_stop(""));
    assert(command["input"]["auto_gain_dbfs"] == 0);
    AssistProtocol owner;
    owner.receive(R"({"type":"auth_ok"})");
    deserializeJson(command, owner.subscribe_control());
    assert(command["entity_ids"][2] == "input_select.voice_device");
    assert(!owner.owns_voice); // Missing helpers must never enable a second microphone.
    assert(owner.receive(R"({"id":1,"type":"event","event":{"a":{"input_select.voice_device":{"s":"johan2"}}}})") == Event::OwnerChanged);
    assert(owner.owns_voice);
    assert(owner.receive(R"({"id":99,"type":"event","event":{"c":{"input_select.voice_device":{"+":{"s":"homedash"}}}}})") == Event::None);
    assert(owner.owns_voice); // A stale subscription cannot revoke the live lease.
    owner.receive(R"({"id":1,"type":"event","event":{"r":["input_button.johan2_assist_start"]}})");
    assert(owner.owns_voice);
    assert(owner.receive(R"({"id":1,"type":"event","event":{"c":{"input_select.voice_device":{"+":{"s":"homedash"}}}}})") == Event::OwnerChanged);
    assert(!owner.owns_voice);
    owner.receive(R"({"id":1,"type":"event","event":{"a":{"input_select.voice_device":{"s":"johan2"}}}})");
    assert(owner.receive(R"({"id":1,"type":"event","event":{"r":["input_select.voice_device"]}})") == Event::OwnerChanged);
    assert(!owner.owns_voice);
    deserializeJson(command, owner.heartbeat());
    assert(command["domain"] == "input_button" && command["service"] == "press");
    assert(command["target"]["entity_id"] == "input_button.johan2_voice_heartbeat");
    deserializeJson(command, owner.pipeline_update("same-assistant"));
    assert(command["service_data"]["value"] == "same-assistant");
    owner.reset();
    assert(!owner.owns_voice && !owner.authenticated);
    std::cout << "Assist protocol tests passed\n";
}
