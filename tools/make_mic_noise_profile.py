#!/usr/bin/env python3
"""Generate a numeric noise profile; source recordings are never copied into the repo.

Requires numpy. Inputs: mic-18 (5..8 s, 100 Hz HP) and mic-27 (3..9 s,
180 Hz HP), both mono s16/16 kHz at gain 16. Correct the quiet recording's
high-pass response before comparison. The resulting profile is referred to the
input of firmware HP/DC processing, in pre-gain PCM sample units.
"""
import argparse
import wave
from pathlib import Path
import numpy as np

RATE, N, HOP = 16000, 512, 256


def read(path, start, end):
    with wave.open(str(path), 'rb') as wav:
        if (wav.getnchannels(), wav.getsampwidth(), wav.getframerate()) != (1, 2, RATE):
            raise ValueError('Expected mono s16 16 kHz WAV')
        pcm = np.frombuffer(wav.readframes(wav.getnframes()), dtype='<i2').astype(float)
    if len(pcm) < end * RATE:
        raise ValueError('Recording too short')
    return pcm[start * RATE:end * RATE] / 16.0


def hp_power(frequency, cutoff):
    if not cutoff:
        return np.ones_like(frequency)
    ratio = np.tan(np.pi * frequency / RATE) / np.tan(np.pi * cutoff / RATE)
    return ratio**4 / (1 + ratio**4)


def spectrum(pcm):
    window = np.sqrt(np.hanning(N + 1)[:-1])
    return np.mean([abs(np.fft.rfft(pcm[i:i + N] * window))**2
                    for i in range(0, len(pcm) - N + 1, HOP)], axis=0)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('noisy', type=Path)
    parser.add_argument('quiet', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    frequency = np.fft.rfftfreq(N, 1 / RATE)
    noisy = spectrum(read(args.noisy, 5, 8))
    quiet = spectrum(read(args.quiet, 3, 9))
    z = np.exp(-2j * np.pi * frequency / RATE)
    dc = abs((255 / 256) * (1 - z) / (1 - (255 / 256) * z))**2
    ref_response = np.maximum(hp_power(frequency, 100) * dc, 1e-6)
    quiet_response = np.maximum(hp_power(frequency, 180) * dc, 1e-6)
    raw_noise = noisy / ref_response
    raw_quiet = quiet / quiet_response
    # Only target bins showing >6 dB excess above the quiet reference. Avoid
    # inverting the poorly resolved extreme low end or touching high frequencies.
    target = (frequency >= 62.5) & (frequency <= 2000) & (raw_noise > 4 * raw_quiet)
    profile = np.where(target, np.maximum(raw_noise - raw_quiet, 0), 0)
    values = ',\n    '.join(', '.join(f'{v:.8e}f' for v in profile[i:i + 6])
                          for i in range(0, len(profile), 6))
    args.output.write_text('''#pragma once
// Generated by tools/make_mic_noise_profile.py. No source audio is embedded.
// mic-18: 5..8 s at HP100; mic-27: 3..9 s at HP180; gain 16, 16 kHz.
// 512-point sqrt-Hann FFT power, normalized to pre-gain/pre-HP PCM units.
inline constexpr float MIC_NOISE_POWER[257] = {
    ''' + values + '\n};\n')
    print(f'Generated {int(target.sum())} targeted frequency bins')


if __name__ == '__main__':
    main()
